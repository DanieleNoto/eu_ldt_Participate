set -euo pipefail

# --- Settings ---------------------------------------------------------------
TEMPLATE_DIR="${TEMPLATE_DIR:-infrastructure/int}"   # where your _%VAR%_ templates live
EXAMPLE_FILE="${EXAMPLE_FILE:-.env.example}"
PREFILL_FILE="${PREFILL_FILE:-}"                     # optional: an existing .env to prefill values

# --- Helpers ----------------------------------------------------------------
die() { echo "ERROR: $*" >&2; exit 1; }

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "Missing required command: $1"
}

collect_vars() {
  # Find tokens like _%MY-VAR%_ and extract MY-VAR
  grep -Rho --exclude-dir='.git' '_%[A-Za-z0-9_\-]\+%_' "$TEMPLATE_DIR" 2>/dev/null \
    | sed -E 's/^_%([A-Za-z0-9_\-]+)%_$/\1/' \
    | sort -u
}

prefill_lookup() {
  # If PREFILL_FILE is provided, return value for a VAR if present
  local var="$1"
  [[ -n "$PREFILL_FILE" && -f "$PREFILL_FILE" ]] || return 1
  # shellcheck disable=SC2046,SC2002
  awk -F= -v k="$var" '
    $0 !~ /^[[:space:]]*#/ && $1 ~ /^[[:space:]]*(export[[:space:]]+)?[A-Za-z0-9_-]+[[:space:]]*$/ {
      gsub(/^[[:space:]]*export[[:space:]]+/,"",$1);
      key=$1; sub(/[[:space:]]+$/, "", key);
      if (key==k) {
        sub(/^[^=]*=/, "", $0);
        print $0; exit 0
      }
    }' "$PREFILL_FILE"
}

# --- Main -------------------------------------------------------------------
require_cmd grep
require_cmd sed
require_cmd sort
require_cmd awk

[[ -d "$TEMPLATE_DIR" ]] || die "Template directory not found: $TEMPLATE_DIR"

VARS="$(collect_vars || true)"

{
  echo "# SPDX-License-Identifier: AGPL-3.0"
  echo "# Copyright (c) 2025, European Commission. Licensed under the AGPL-3.0"
  echo "# Authors: Gianfranco Cedro"
  echo "#"
  echo "# Autogenerated by generate-env-example.sh"
  echo "# Discovered in: $TEMPLATE_DIR"
  echo "# Fill the values and save as .env for rendering."
  echo

  if [[ -z "${VARS}" ]]; then
    echo "# No _%VAR%_ placeholders found."
  else
    while IFS= read -r var; do
      if val="$(prefill_lookup "$var")"; then
        echo "${var}=${val}"
      else
        echo "${var}="
      fi
    done <<< "$VARS"
  fi
} > "$EXAMPLE_FILE"

echo "✅ Generated $EXAMPLE_FILE with $(echo "$VARS" | wc -l) variables"
echo "📋 Found placeholders from: $TEMPLATE_DIR"
echo "💡 Fill the values and save as .env for local development"